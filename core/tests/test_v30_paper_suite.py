def test_experiment_design_has_exact_default_and_quick_bounds():
    parser = paper_suite.build_parser()
    profile = ["--suite-profile", "legacy_v30"]
    default_design = paper_suite.build_experiment_design(
        parser.parse_args(profile)
    )
    quick_design = paper_suite.build_experiment_design(
        parser.parse_args([*profile, "--quick"])
    )
    geometry_design = paper_suite.build_experiment_design(
        parser.parse_args([*profile, "--quick", "--include-geometry"])
    )

    assert default_design.suite_profile == "legacy_v30"
    assert default_design.core_run_count == 48
    assert default_design.ablation_run_count == 15
    assert default_design.rul_simulation_count == 240
    assert len(default_design.core_policies) == 12
    assert len(default_design.core_scenarios) == 4
    assert len(default_design.ablation_configurations) == 5

    assert quick_design.years == 0.02
    assert quick_design.rul_start_year == 0.02
    assert quick_design.rul_horizon_years == 0.02
    assert quick_design.core_run_count == 2
    assert quick_design.ablation_run_count == 5
    assert quick_design.rul_simulation_count == 2

    assert geometry_design.core_run_count == quick_design.core_run_count
    assert geometry_design.rul_simulation_count == quick_design.rul_simulation_count
    assert geometry_design.ablation_run_count == quick_design.ablation_run_count + 1
    geometry_configurations = [
        configuration
        for configuration in geometry_design.ablation_configurations
        if configuration.contact_model == "geometry"
    ]
    assert len(geometry_configurations) == 1
    assert geometry_configurations[0].applicable_policies == ("adaptive",)


def test_quick_suite_writes_expected_package_and_bounded_rows(tmp_path):
    pytest.importorskip("matplotlib")
    results_dir = tmp_path / "paper_suite"
    _run_quick(results_dir)

    raw_dir = results_dir / "raw"
    tables_dir = results_dir / "tables"
    figures_dir = results_dir / "figures"
    paper_dir = results_dir / "paper"
    assert all(path.is_dir() for path in (
        raw_dir, tables_dir, figures_dir, paper_dir
    ))
    assert RAW_BASE_FILES | RAW_RUL_FILES <= _names(raw_dir)
    assert TABLE_BASE_FILES | TABLE_RUL_FILES <= _names(tables_dir)
    assert PAPER_FILES <= _names(paper_dir)
    assert BASE_FIGURES | RUL_FIGURES <= _names(figures_dir)

    core_rows = _read_csv(raw_dir / "core_summary.csv")
    ablation_rows = _read_csv(raw_dir / "ablation_raw.csv")
    rul_rows = _read_csv(raw_dir / "rul_samples.csv")
    assert len(core_rows) == 2
    assert {row["policy"] for row in core_rows} == {
        "adaptive", "survival_first"
    }
    assert {row["scenario"] for row in core_rows} == {"nominal"}
    assert len(ablation_rows) == 5
    assert {row["policy"] for row in ablation_rows} == {"adaptive"}
    assert len(rul_rows) == 2
    assert {row["policy"] for row in rul_rows} == {
        "adaptive", "survival_first"
    }

    for filename in BASE_FIGURES | RUL_FIGURES:
        image = (figures_dir / filename).read_bytes()
        assert image.startswith(b"\x89PNG\r\n\x1a\n")
    for filename in TABLE_BASE_FILES | TABLE_RUL_FILES:
        if filename.endswith(".md"):
            assert "|" in (tables_dir / filename).read_text(encoding="utf-8")
    for filename in PAPER_FILES:
        assert (paper_dir / filename).read_text(encoding="utf-8").strip()


def test_quick_skip_rul_omits_rul_outputs_cleanly(tmp_path):
    results_dir = tmp_path / "paper_suite_no_rul"
    for directory in ("raw", "tables", "figures", "paper"):
        (results_dir / directory).mkdir(parents=True, exist_ok=True)
    for filename in RAW_RUL_FILES:
        (results_dir / "raw" / filename).write_text("stale", encoding="utf-8")
    for filename in TABLE_RUL_FILES:
        (results_dir / "tables" / filename).write_text(
            "stale", encoding="utf-8"
        )
    for filename in BASE_FIGURES | RUL_FIGURES:
        (results_dir / "figures" / filename).write_text(
            "stale", encoding="utf-8"
        )
    _run_quick(results_dir, "--skip-rul", "--skip-plots")

    raw_dir = results_dir / "raw"
    tables_dir = results_dir / "tables"
    figures_dir = results_dir / "figures"
    paper_dir = results_dir / "paper"
    assert all(path.is_dir() for path in (
        raw_dir, tables_dir, figures_dir, paper_dir
    ))
    assert RAW_BASE_FILES <= _names(raw_dir)
    assert RAW_RUL_FILES.isdisjoint(_names(raw_dir))
    assert TABLE_BASE_FILES <= _names(tables_dir)
    assert TABLE_RUL_FILES.isdisjoint(_names(tables_dir))
    assert not list(figures_dir.glob("*.png"))
    assert PAPER_FILES <= _names(paper_dir)
    assert len(_read_csv(raw_dir / "core_summary.csv")) == 2
    assert len(_read_csv(raw_dir / "ablation_raw.csv")) == 5


def test_quick_skip_plots_omits_figures_but_keeps_rul_outputs(tmp_path):
    results_dir = tmp_path / "paper_suite_no_plots"
