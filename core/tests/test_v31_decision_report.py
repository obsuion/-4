import csv
from pathlib import Path

import decision_report
import paper_suite
from ops_sim.models import Mode


TRACE_FILES = {
    "decision_trace.csv",
    "risk_trace.csv",
    "option_assessments.csv",
}
SUMMARY_FILES = {
    "failure_attribution.csv",
    "decision_summary.md",
}


def read_rows(path: Path) -> list[dict[str, str]]:
    with path.open(newline="", encoding="utf-8") as handle:
        return list(csv.DictReader(handle))


def test_decision_report_writes_all_outputs_and_required_fields(tmp_path):
    assert decision_report.main([
        "--years", "0.001",
        "--policy", "adaptive",
        "--scenario", "nominal",
        "--operator-view", "delayed_telemetry",
        "--planning-model", "risk_aware",
        "--maneuver-model", "stationkeeping_proxy",
        "--orbit-evolution-model", "drift_proxy",
        "--results-dir", str(tmp_path),
    ]) == 0

    assert TRACE_FILES | SUMMARY_FILES <= {
        path.name for path in tmp_path.iterdir() if path.is_file()
    }
    decisions = read_rows(tmp_path / "decision_trace.csv")
    risks = read_rows(tmp_path / "risk_trace.csv")
    options = read_rows(tmp_path / "option_assessments.csv")
    attribution = read_rows(tmp_path / "failure_attribution.csv")
    assert len(decisions) == len(risks) > 0
    assert len(options) == len(decisions) * len(Mode)
    assert len(attribution) == 1
    assert {
        "selected_mode", "executed_mode", "planned_mode", "main_reason",
        "main_risk_driver", "active_constraints", "rejected_alternatives",
    } <= set(decisions[0])
    assert {
        "power_risk", "storage_risk", "fuel_risk", "debris_risk",
        "telemetry_staleness_risk",
    } <= set(risks[0])
    assert {
        "mode", "feasible", "rejection_reason", "risk_penalty",
        "utility_hint",
    } <= set(options[0])
    assert "proxy diagnostics" in (
        tmp_path / "decision_summary.md"
    ).read_text(encoding="utf-8")


def test_summary_only_removes_hourly_traces_but_keeps_summary(tmp_path):
    for filename in TRACE_FILES:
        (tmp_path / filename).write_text("stale", encoding="utf-8")
    assert decision_report.main([
        "--years", "0.001",
        "--summary-only",
        "--results-dir", str(tmp_path),
    ]) == 0

    assert all(not (tmp_path / filename).exists() for filename in TRACE_FILES)
    assert all((tmp_path / filename).exists() for filename in SUMMARY_FILES)


def test_max_rows_limits_trace_hours_and_assessment_groups(tmp_path):
    assert decision_report.main([
        "--years", "0.002",
        "--max-rows", "2",
        "--results-dir", str(tmp_path),
    ]) == 0

    decisions = read_rows(tmp_path / "decision_trace.csv")
    risks = read_rows(tmp_path / "risk_trace.csv")
    options = read_rows(tmp_path / "option_assessments.csv")
    assert len(decisions) == len(risks) == 2
    assert len(options) == 2 * len(Mode)
    assert {row["hour"] for row in options} == {"0", "1"}


def test_paper_suite_decision_report_is_default_off_and_bounded_opt_in(tmp_path):
    default_dir = tmp_path / "default"
    included_dir = tmp_path / "included"
    common = ["--quick", "--skip-plots", "--skip-rul"]
    assert paper_suite.main([
        *common, "--results-dir", str(default_dir)
    ]) == 0
    assert not (default_dir / "decision").exists()

    assert paper_suite.main([
        *common,
        "--include-decision-report",
        "--results-dir", str(included_dir),
    ]) == 0
    decision_dir = included_dir / "decision"
    assert TRACE_FILES | SUMMARY_FILES <= {
        path.name for path in decision_dir.iterdir() if path.is_file()
    }
    assert len(read_rows(decision_dir / "decision_trace.csv")) == round(
        paper_suite.QUICK_YEARS * 8766
    )
    results_markdown = (
        included_dir / "paper" / "results_autogenerated.md"
    ).read_text(encoding="utf-8")
    assert "decision/decision_summary.md" in results_markdown


def test_readme_documents_v31_outputs_and_boundaries():
    readme = Path("README.md").read_text(encoding="utf-8")
    normalized = " ".join(readme.split())
    assert "## V3.1 decision and risk explanation layer" in readme
    assert "`decision_report.py`" in readme
    for filename in TRACE_FILES | SUMMARY_FILES:
        assert f"`{filename}`" in readme
    assert "--include-decision-report" in readme
    assert "does not add new physics or smarter optimization" in normalized
    assert "not probabilities" in normalized
    assert "not validated operator reasoning" in normalized
