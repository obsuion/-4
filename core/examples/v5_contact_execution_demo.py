ROOT = Path(__file__).resolve().parents[1]


def contact_case(*, bits=(10, 8, 4, 40, 7), partials=((0, 4), (3, 5)), rate=3, duration=10):
    c = old.physical.reference_context()
    cfg = c.inputs.spacecraft_configuration
    c.inputs = replace(c.inputs, spacecraft_configuration=replace(cfg, communications=replace(cfg.communications,
        nominal_downlink_data_rate_bps=old.physical.parameter_value(cfg.communications.nominal_downlink_data_rate_bps, float(rate)))))
    records = tuple(old.physical.record("task04b-record-"+str(i), float(total)) for i,total in enumerate(bits))
    c.spacecraft_state.data_storage = DataStorageState(records)
    c.ground_data_delivery_state = GroundDataDeliveryState(tuple(
        DownlinkTransferProgress(records[i].record_id, float(progress)) for i,progress in partials), ())
    tx = replace(old.physical.physical_inputs(c, sunlit=False),
        baseline_loads=PowerLoadBreakdown(12.,0.,0.,0.,0.,0.,0.), solar_degradation_forcing=None)
    idle = StandbyInputs(tx.baseline_loads, tx.sunlit, tx.incidence_angle_deg, tx.routing_config,
        tx.thermal_inputs, tx.external_heat_sources, tx.solar_degradation_forcing,
        "Synthetic 12 W essential baseline; same constant environment, transmitter off.")
    contact = replace(old.physical.contact(c, "task04b-contact-1"), end_time_seconds=100+duration)
    plan = ContactPlan(contact, tuple(r.record_id for r in records[:3]), tx, idle)
    return c, plan, old.policy(c)


def build_demo_state(level=2):
    c, first, policy = contact_case()
    records = c.spacecraft_state.data_storage.stored_records
    from ops_sim.v5.ids import GroundContactId
    second = replace(first, contact=replace(first.contact, contact_id=GroundContactId("task04b-contact-2"),
        start_time_seconds=110, end_time_seconds=115), record_ids=(records[3].record_id,))
    third = replace(first, contact=replace(first.contact, contact_id=GroundContactId("task04b-contact-3"),
        start_time_seconds=115, end_time_seconds=125), record_ids=(records[3].record_id, records[4].record_id))
    previous = old.physical.storage._previous_execution()
    consumed = ConsumedContacts(())
    program = ContactProgram(5, CheckpointState.from_context(c), previous, consumed, policy, IntegrationPolicy(level),
        (first, second, third), (
            "Synthetic integer-bit/rate service: fixed explicit order; no scheduling or calibration.",
            "Constant contact environment, 12 W baseline, 36 W transmitter only during exact data service.",
            "Exact rational internal boundaries; binary64 Euler physics; sampled protection only.",
            "Completed-contact restart only; original serviceable contact identity remains unchanged.",
        ))
    return ContactState(c, program, ContactMemory((), consumed, previous))


def physical_scenario_digest(state):
    p = state.program
    return content_digest("task04b-physical-scenario-v1", (state.context.inputs, p.initial_checkpoint,
        p.initial_previous_execution, p.initial_consumed_contacts, p.policy, p.plans, p.assumptions))


def reject_consumed_replay(state):
    if not state.memory.outcomes:
        return None
    before = canonical_content(CheckpointState.from_context(state.context))
    try:
        execute_contact_plan(state.context, state.program.plans[0], consumed_contacts=state.memory.consumed_contacts,
            policy=state.program.policy, integration=state.program.integration)
    except ValueError as error:
        if "already consumed" not in str(error):
            raise
        assert canonical_content(CheckpointState.from_context(state.context)) == before
        return str(error)
    raise AssertionError("consumed contact was allowed to execute again")


def summarize(state):
    readable = []
    for outcome in state.memory.outcomes:
        segments = []
        for segment in outcome.segments:
            trace = segment.trace
            h = float(trace.end_offset.fraction-trace.start_offset.fraction)
            segments.append({"start_offset_s":str(trace.start_offset.fraction), "end_offset_s":str(trace.end_offset.fraction),
                "tx_on":segment.transmitter_on, "record_id":None if segment.record_id is None else segment.record_id.value,
                "average_load_w":segment.accounting.requested_load_wh*3600/h,
                "average_generation_w":segment.accounting.generation_wh*3600/h,
                "battery_start_wh":trace.samples[0].battery_energy_wh, "battery_end_wh":trace.samples[-1].battery_energy_wh,
                "temperatures_end_k":{n.value:t for n,t in trace.samples[-1].temperatures_k}})
        readable.append({"contact_id":outcome.contact.contact_id.value,
            "interval_s":[outcome.contact.start_time_seconds,outcome.contact.end_time_seconds],
            "requested_order":[i.value for i in outcome.requested_order], "segments":segments,
            "services":[{"record":s.record.record_id.value,"before_bits":s.progress_before_bits,
                "transmitted_bits":s.transmitted_bits,"after_bits":s.progress_after_bits,"completed":s.completed,
                "exact_completion_offset_s":str(s.end_offset.fraction) if s.completed else None,
                "conservative_completion_time_s":s.completion_time_seconds} for s in outcome.services],
            "tx_on_s":str(outcome.tx_on_seconds.fraction), "residual_idle_s":str(outcome.idle_seconds.fraction),
            "denied_record":None if outcome.denied_record_id is None else outcome.denied_record_id.value,
            "protection_reasons":[[r.value for r in a.availability.reasons] for a in outcome.attempts],
            "fdir":outcome.fdir_state.value})
    return {"input_digest":experiment_input_digest(state.context.inputs,state.program),
        "physical_scenario_digest":physical_scenario_digest(state),
        "checkpoint":CheckpointState.from_context(state.context).to_dict(), "memory":canonical_content(state.memory),
        "trace":readable, "consumed_replay_rejection":reject_consumed_replay(state),
        "metrics":{"contacts":len(state.memory.outcomes),"transmitted_bits":state.memory.transmitted_bits,
            "numerical_substeps":state.memory.numerical_substeps,"evaluated_eps_substeps":state.memory.evaluated_eps_substeps,
            "stored_records":len(state.context.spacecraft_state.data_storage.stored_records),
            "partial_records":len(state.context.ground_data_delivery_state.partial_transfers),
            "completed_records":len(state.context.ground_data_delivery_state.completed_deliveries),
            "clock_seconds":state.context.simulation_time_seconds,"outer_steps":state.context.diagnostics.completed_steps}}


def numerical_reference():
    c,plan,policy = contact_case()
    result = execute_contact_plan(c,plan,consumed_contacts=ConsumedContacts(()),policy=policy,integration=IntegrationPolicy(2))
    out = result.outcome
    # Independent literal arithmetic: (10-4)+8+4 bits at 3 bit/s.
    tx = Fraction(18,3);idle = Fraction(10)-tx
    bus = (48*tx+12*idle)/3600
    throughput = bus/Fraction(4,5);loss = throughput-bus
    assert out.transmitted_bits==18 and out.tx_on_seconds.fraction==tx and out.idle_seconds.fraction==idle
    expected={"requested_load_wh":bus,"served_load_wh":bus,"generation_wh":0,"unmet_load_wh":0,
              "throughput_wh":throughput,"conversion_loss_wh":loss,"unavailable_energy_wh":0}
    rows=[]
    for name,value in expected.items():
        actual=getattr(out.accounting,name);value=float(value);bound=64*ulp(value or 1.)
        assert abs(actual-value)<=bound,(name,actual,value)
        rows.append(dict(quantity=name,units="Wh",expected=value,actual=actual,bound=bound,error=abs(actual-value)))
    expected_energy=float(Fraction(80)-throughput)
    assert abs(c.spacecraft_state.battery.energy_wh-expected_energy)<=16*ulp(80.)
    rows.append(dict(quantity="end_battery_energy",units="Wh",expected=expected_energy,
        actual=c.spacecraft_state.battery.energy_wh,bound=16*ulp(80.),error=abs(c.spacecraft_state.battery.energy_wh-expected_energy)))
    # Isolated nonradiating nodes, literal routed and external heat.
    temps={n.node_id.value:n.temperature_k for n in c.spacecraft_state.thermal.node_states}
    for name,value in {"bus":Fraction(300)+(26*tx+8*idle)/3600,
                       "payload":Fraction(300)+Fraction(30,3600),
                       "battery":Fraction(300)+loss+Fraction(10,3600)}.items():
        expected_k=float(value);bound=32*ulp(300.)
        assert abs(temps[name]-expected_k)<=bound,(name,temps[name],expected_k)
        rows.append(dict(quantity=name+"_temperature",units="K",expected=expected_k,actual=temps[name],bound=bound,error=abs(temps[name]-expected_k)))
    return {"reference":"Independent rational constant-power/time and isolated-node balances; synthetic assumptions.",
        "transmitted_bits":18,"tx_on_s":str(tx),"idle_s":str(idle),"rows":rows,
        "whole_contact_tx_energy_wh":float(Fraction(48*10,3600)),"outer_clock_s":c.simulation_time_seconds}


def main(argv=None):
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--level",type=int,default=2)
    parser.add_argument("--resume",type=Path)
    parser.add_argument("--stop-after",type=int)
    parser.add_argument("--bundle-output",type=Path)
    parser.add_argument("--references",action="store_true")
    parser.add_argument("--output",type=Path,required=True)
    args=parser.parse_args(argv)
    if args.references:
        result=numerical_reference()
    else:
        state=build_demo_state(args.level) if args.resume is None else ExperimentBundle.from_json(
            args.resume.read_text(encoding="utf-8")).restore(repository_root=ROOT)
        stop=len(state.program.plans) if args.stop_after is None else args.stop_after
        if not len(state.memory.outcomes)<=stop<=len(state.program.plans):parser.error("invalid completed-contact boundary")
        while len(state.memory.outcomes)<stop:state=advance_contact_continuation(state)
        if args.bundle_output:args.bundle_output.write_text(create_bundle(state,repository_root=ROOT).to_json(),encoding="utf-8")
        result=summarize(state)
    args.output.write_text(json.dumps(result,ensure_ascii=False,sort_keys=True,allow_nan=False,indent=2),encoding="utf-8")


if __name__=="__main__":
    main()
